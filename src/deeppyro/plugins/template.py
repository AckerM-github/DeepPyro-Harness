"""Scaffold a new user bundle for the self-extension loop.

plugin_create and PluginManager.create_bundle write a minimal but working
bundle: bundle.toml, plugin.py and README.md. The generated plugin declares a
pydantic Config with one volatile field, injects the tools service and
registers one sample tool, so it demonstrates the plugin API surface an agent
can extend.

The files are generated in a temporary directory and validated with
kernel.composition.load_bundle before they are copied to the destination, so a
scaffold is never written with an invalid bundle.toml.
"""

from __future__ import annotations

import json
import re
import shutil
import tempfile
from pathlib import Path

from deeppyro.kernel.composition import CompositionError, load_bundle

from .bundles import validate_bundle_id
from .errors import PluginError

_BUNDLE_VERSION = "0.1.0"
_DEFAULT_ORDER = 500
_SPLIT = re.compile(r"[^0-9A-Za-z]+")

_PLUGIN_SOURCE = '''"""Sample plugin generated by the DeepPyro self-extension loop.

Edit this file to add your own tools, commands, prompt sections or providers.
Restart the TUI after code changes; the configuration in SampleConfig can be
edited with settings_read and settings_write.
"""

from __future__ import annotations

from typing import Any, ClassVar

from pydantic import BaseModel

from deeppyro.api import Plugin
from deeppyro.core.protocols import ToolContext, ToolResult
from deeppyro.tools.base import BaseTool, make_parameters


class SampleConfig(BaseModel):
    greeting: str = "hello from the sample plugin"
    apiKey: str = ""


class SampleGreetingTool(BaseTool):
    name = "sample_greeting"
    description = "Return the greeting configured for the sample plugin."
    parallel_safe = False
    parameters = make_parameters({})

    def __init__(self, greeting: str) -> None:
        self.greeting = greeting

    async def run(self, args: dict[str, Any], ctx: ToolContext) -> ToolResult:
        return ToolResult(text=self.greeting)


class __CLASS__(Plugin):
    plugin_id = __PLUGIN_ID__
    version = "0.1.0"
    description = __DESCRIPTION__
    Config = SampleConfig
    volatile: ClassVar[tuple[str, ...]] = ("greeting",)
    inject: ClassVar[list[str]] = ["tools"]

    def setup(self, ctx: Any, config: Any) -> None:
        greeting = config.greeting if config is not None else "hello from the sample plugin"
        ctx.register_tool(lambda _cfg, _workspace: [SampleGreetingTool(greeting)])
'''

_README = """# __NAME__

Generated by the DeepPyro self-extension loop (plugin_create).

Files:
- bundle.toml: bundle metadata and one plugin row
- plugin.py: plugin class, pydantic Config and one sample tool

Install and enable:
1. Run plugin_manager with action=install and source=<this directory>.
2. Run plugin_manager with action=set, id=__BUNDLE_ID__, enabled=true.
3. Restart the TUI so the kernel mounts the new bundle.

Configure:
Use settings_read and settings_write. Volatile fields declared on the plugin
class, such as greeting, apply live when the kernel service exposes
apply_plugin_config; everything else takes effect on the next boot.

Extend:
Add tools, prompt sections, commands or providers in plugin.py with the
ctx.register_* methods, then restart.
"""


def _class_prefix(bundle_id: str) -> str:
    parts = [part for part in _SPLIT.split(bundle_id) if part]
    prefix = "".join(part[0].upper() + part[1:] for part in parts)
    if not prefix:
        prefix = "Sample"
    if prefix[0].isdigit():
        prefix = "Sample" + prefix
    return prefix


def _manifest(bundle_id: str, name: str, plugin_class: str, api_version: int) -> str:
    return (
        "[bundle]\n"
        f"id = {json.dumps(bundle_id, ensure_ascii=False)}\n"
        f"name = {json.dumps(name, ensure_ascii=False)}\n"
        f'version = "{_BUNDLE_VERSION}"\n'
        f"api_version = {api_version}\n"
        f"order = {_DEFAULT_ORDER}\n"
        "critical = false\n"
        "\n"
        "[[plugins]]\n"
        f"id = {json.dumps(bundle_id, ensure_ascii=False)}\n"
        f"plugin = {json.dumps('plugin.py:' + plugin_class, ensure_ascii=False)}\n"
    )


def bundle_template(
    bundle_id: str = "demo-bundle",
    name: str = "",
    *,
    api_version: int = 1,
) -> dict[str, str]:
    """Return the scaffolded files keyed by relative path, without writing."""
    valid_id = validate_bundle_id(bundle_id)
    plugin_class = _class_prefix(valid_id) + "Plugin"
    display_name = name.strip() or valid_id
    plugin_source = (
        _PLUGIN_SOURCE.replace("__CLASS__", plugin_class)
        .replace("__PLUGIN_ID__", json.dumps(valid_id, ensure_ascii=False))
        .replace("__DESCRIPTION__", json.dumps(display_name + " plugin", ensure_ascii=False))
    )
    readme = _README.replace("__NAME__", display_name).replace("__BUNDLE_ID__", valid_id)
    return {
        "bundle.toml": _manifest(valid_id, display_name, plugin_class, api_version),
        "plugin.py": plugin_source,
        "README.md": readme,
    }


def create_bundle(
    dest: str | Path,
    bundle_id: str,
    name: str = "",
    *,
    api_version: int = 1,
) -> Path:
    """Validate and write a new bundle scaffold at dest; return the directory."""
    target = Path(dest).expanduser()
    if target.exists() and not target.is_dir():
        raise PluginError(f"bundle destination {target} is not a directory")
    if target.is_dir() and any(target.iterdir()):
        raise PluginError(f"bundle destination {target} is not empty")
    files = bundle_template(bundle_id, name, api_version=api_version)
    staging = Path(tempfile.mkdtemp(prefix="deeppyro-bundle-"))
    try:
        for relative, text in files.items():
            (staging / relative).write_text(text, encoding="utf-8")
        try:
            load_bundle(staging)
        except CompositionError as exc:
            raise PluginError(f"generated bundle {bundle_id!r} is invalid: {exc}") from exc
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            shutil.rmtree(target)
        try:
            shutil.copytree(staging, target)
        except OSError as exc:
            raise PluginError(f"cannot write bundle {bundle_id!r} to {target}: {exc}") from exc
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return target


__all__ = ["bundle_template", "create_bundle"]
